            pipeline and converted to PLINK-compatible format. Analyses were restricted to autosomal bi-allelic A/C/G/T
            SNPs passing sample- and variant-level quality control.
          </p>
          <p>
            Association testing used REGENIE in a two-step framework. Step 1 fit whole-genome regression models to
            account for polygenic background, and step 2 tested single-variant associations for each residualized,
            normalized imaging phenotype. Pooled-sample summary statistics were used for primary discovery and most
            downstream analyses unless otherwise indicated.
          </p>
        </div>

