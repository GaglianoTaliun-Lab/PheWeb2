          <h2>3. Trait Processing</h2>
          <hr>
          <p>
            Quantitative traits were generated by fitting trait-specific linear models and applying rank-based inverse
            normal transformation to the residuals. In pooled analyses, covariates included sex, age, age squared,
            sex-by-age terms, assessment center, WGS batch, and 20 genetic principal components.
          </p>
          <p>
            BMI- and height-adjusted adiposity traits additionally included BMI and height from the same imaging
